# One-off generator: emit the blended piece values and piece-square tables from
# constants.py as C++ arrays, in the C++ engine's LERF-from-White orientation
# (a1=0 .. h8=63). Run from python/:  python gen_eval_tables.py > ../src/eval_tables.inc
#
# Python tables are indexed [row][col] with row 0 = rank 8, col 0 = a-file, and
# evaluate() uses table[r][c] for White. A LERF square sq has rank=sq>>3,
# file=sq&7, so its Python row is (7-rank). Thus white_pst[sq] = table[7-rank][file].
# Black reuses the same array mirrored vertically (sq ^ 56), handled in C++.

from constants import (
    PIECE_VALUES, PAWN, KNIGHT, BISHOP, ROOK, QUEEN,
    PAWN_TABLE, KNIGHT_TABLE, BISHOP_TABLE, ROOK_TABLE, QUEEN_TABLE,
    KING_TABLE, KING_END_TABLE,
)

def to_lerf(table):
    out = [0] * 64
    for sq in range(64):
        rank, file = sq >> 3, sq & 7
        out[sq] = table[7 - rank][file]
    return out

def emit(name, table):
    vals = to_lerf(table)
    print(f"constexpr int16_t {name}[64] = {{")
    for rank in range(7, -1, -1):  # print rank 8 down to rank 1 for readability
        row = ", ".join(f"{vals[rank*8 + f]:4d}" for f in range(8))
        print(f"    {row},   // rank {rank + 1}")
    print("};\n")

print("// AUTO-GENERATED by python/gen_eval_tables.py from the Python engine's")
print("// Texel-blended constants. Do not edit by hand; regenerate instead.")
print("// Indexed by LERF square (a1=0..h8=63), from White's perspective.\n")

pv = PIECE_VALUES
print("// Blended piece values (centipawns). Index by PieceType 0..5.")
print("constexpr int PIECE_VALUE[6] = {")
print(f"    {pv[PAWN]}, {pv[KNIGHT]}, {pv[BISHOP]}, {pv[ROOK]}, {pv[QUEEN]}, 0,")
print("};  // Pawn, Knight, Bishop, Rook, Queen, King\n")

emit("PST_PAWN",     PAWN_TABLE)
emit("PST_KNIGHT",   KNIGHT_TABLE)
emit("PST_BISHOP",   BISHOP_TABLE)
emit("PST_ROOK",     ROOK_TABLE)
emit("PST_QUEEN",    QUEEN_TABLE)
emit("PST_KING",     KING_TABLE)
emit("PST_KING_END", KING_END_TABLE)
